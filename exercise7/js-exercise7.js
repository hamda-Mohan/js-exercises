let colors = ["red", "green", "blue"];
console.log(colors);

//push method
colors.push("yellow");
console.log(colors);

//pop method
colors.pop();
console.log(colors);    

//unshift method
colors.unshift("purple");
console.log(colors);

//shift method
colors.shift();
console.log(colors);

//length property
console.log(colors.length);