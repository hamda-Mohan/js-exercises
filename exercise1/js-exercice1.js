let x = 7 ;
let y = 3 ;

// Arithmetic operators

console.log(x + y); // Addition 10
console.log(x - y); // Subtraction 4
console.log(x * y); // Multiplication 21
console.log(x / y); // Division 2.3333
console.log(x % y); // Modulus 1
console.log(x++);   // Post-increment 7
console.log(++y);   // Pre-increment 4
console.log(x--);  // Post-decrement 8
console.log(--y);  // Pre-decrement 3
